import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createTestDatabase} from './helpers/d1.mjs';
import {createHandler} from '../server/auth.mjs';
test('PostgreSQL authentication and authorization lifecycle',async()=>{
 const db=await createTestDatabase({migrations:['0001_schema.sql']});
 const handler=createHandler(db);
 const call=(path,method='GET',body, cookie='',origin='https://lms.test')=>handler(new Request('https://lms.test/api'+path,{method,headers:{'content-type':'application/json',origin,cookie},...(body?{body:JSON.stringify(body)}:{})}),{ip:'test-ip'});
 const account={email:'student@example.com',name:'학생 <script>',password:'A-long-test-password'};
 assert.equal((await call('/admin/users')).status,401);
 assert.equal((await call('/register','POST',account,'','https://evil.test')).status,403);
 assert.equal((await call('/register','POST',{...account,password:'short'})).status,400);
 assert.equal((await call('/register','POST',{...account,role:'admin'})).status,201);
 let row=(await db.query('SELECT * FROM app_users')).rows[0];
 assert.equal(row.role,'student');assert.notEqual(row.password_hash,account.password);
 assert.equal((await call('/register','POST',account)).status,409);
 assert.equal((await call('/login','POST',{...account,password:'wrong-password'})).status,401);
 let res=await call('/login','POST',account),cookie=res.headers.get('set-cookie').split(';')[0];
 assert.equal(res.status,200);assert.match(res.headers.get('set-cookie'),/HttpOnly; Secure; SameSite=Lax/);
 assert.equal((await call('/admin/users','GET',null,cookie)).status,403);
 let me=await (await call('/me','GET',null,cookie)).json();assert.equal(me.user.name,account.name);assert.equal(me.user.password_hash,undefined);
 await call('/logout','POST',{},cookie);assert.equal((await call('/me','GET',null,cookie)).status,401);
 const admin={email:'teacher@example.com',name:'강사',password:'Teacher-test-password'};
 await call('/register','POST',admin);
 await db.query("UPDATE app_users SET role='admin' WHERE email=$1",[admin.email]);
 res=await call('/login','POST',admin);const adminCookie=res.headers.get('set-cookie').split(';')[0];
 res=await call('/admin/users','GET',null,adminCookie);assert.equal(res.status,200);assert.equal((await res.json()).total,2);
 res=await call('/login','POST',account);cookie=res.headers.get('set-cookie').split(';')[0];
 assert.equal((await call('/admin/users/'+row.id,'PATCH',{active:false},adminCookie)).status,200);
 assert.equal((await call('/me','GET',null,cookie)).status,401);
 assert.equal((await call('/login','POST',account)).status,401);
 assert.equal((await call('/admin/users/'+row.id,'PATCH',{active:true},adminCookie)).status,200);
 assert.equal((await call('/me','GET',null,cookie)).status,401,'reactivation must not restore old session');
 assert.equal((await call('/login','POST',account)).status,200);
 const aid=(await db.query('SELECT id FROM app_users WHERE email=$1',[admin.email])).rows[0].id;
 assert.equal((await call('/admin/users/'+aid,'PATCH',{active:false},adminCookie)).status,400);
 res=await call('/admin/users?q=student','GET',null,adminCookie);assert.equal((await res.json()).total,1);
 res=await call('/login','POST',admin);const expiryCookie=res.headers.get('set-cookie').split(';')[0];
 await db.query("UPDATE app_sessions SET expires_at=strftime('%Y-%m-%dT%H:%M:%fZ','now','-1 hour')");
 assert.equal((await call('/me','GET',null,expiryCookie)).status,401);
 await db.query('DELETE FROM auth_limits');
 for(let i=0;i<12;i++)assert.equal((await call('/login','POST',{...account,password:'incorrect-password'})).status,401);
 assert.equal((await call('/login','POST',account)).status,429);
});
test('administrator student creation, editing, reset and permission boundaries',async()=>{
 const db=await createTestDatabase({migrations:['0001_schema.sql']});
 const handler=createHandler(db);
 const call=(path,method='GET',body,cookie='')=>handler(new Request('https://lms.test/api'+path,{method,headers:{'content-type':'application/json',origin:'https://lms.test',cookie},...(body?{body:JSON.stringify(body)}:{})}),{ip:'admin-test'});
 const owner={name:'Teacher',email:'owner@example.com',password:'Owner-password-2026'};
 await call('/register','POST',owner);await db.query("UPDATE app_users SET role='admin' WHERE email=$1",[owner.email]);
 let res=await call('/login','POST',owner);const ac=res.headers.get('set-cookie').split(';')[0];
 const student={name:'Student',email:'new@example.com',password:'Student-password-2026'};
 assert.equal((await call('/admin/users','POST',student)).status,401);
 res=await call('/admin/users','POST',{...student,role:'admin'},ac);assert.equal(res.status,201);const u=(await res.json()).user;assert.equal(u.role,'student');assert.equal(u.password_hash,undefined);
 assert.equal((await call('/admin/users','POST',student,ac)).status,409);
 assert.equal((await call('/admin/users','POST',{...student,email:'second@example.com',password:'short'},ac)).status,400);
 res=await call('/login','POST',student);let sc=res.headers.get('set-cookie').split(';')[0];
 assert.equal((await call('/admin/users','POST',{...student,email:'other@example.com'},sc)).status,403);
 assert.equal((await call('/admin/users/'+u.id,'PATCH',{name:'Hack',email:'hack@example.com'},sc)).status,403);
 assert.equal((await call('/admin/users/'+u.id+'/password','POST',{password:'Unauthorized-2026'},sc)).status,403);
 assert.equal((await call('/admin/users/'+u.id,'PATCH',{name:'Student',email:owner.email},ac)).status,409);
 assert.equal((await call('/admin/users/'+u.id,'PATCH',{name:'Updated',email:'updated@example.com',role:'admin'},ac)).status,200);
 assert.equal((await call('/me','GET',null,sc)).status,401);
 assert.equal((await call('/login','POST',student)).status,401);
 res=await call('/login','POST',{...student,email:'updated@example.com'});assert.equal(res.status,200);sc=res.headers.get('set-cookie').split(';')[0];
 assert.equal((await call('/admin/users/'+u.id+'/password','POST',{password:'Replacement-2026'},ac)).status,200);
 assert.equal((await call('/me','GET',null,sc)).status,401);
 assert.equal((await call('/login','POST',{...student,email:'updated@example.com'})).status,401);
 res=await call('/login','POST',{email:'updated@example.com',password:'Replacement-2026'});assert.equal(res.status,200);const updated=(await res.json()).user;assert.equal(updated.name,'Updated');assert.equal(updated.role,'student');
 const ownerId=(await db.query('SELECT id FROM app_users WHERE email=$1',[owner.email])).rows[0].id;
 assert.equal((await call('/admin/users/'+ownerId+'/password','POST',{password:'Replacement-2026'},ac)).status,400);
 assert.equal((await call('/admin/users/'+ownerId,'PATCH',{name:'Changed',email:'changed@example.com'},ac)).status,400);
});
